"""Preliminary validation / deficiency report (reportlab). Advisory; no official emblems."""
from __future__ import annotations

import io
from datetime import datetime, timezone
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    KeepTogether,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

NAVY = colors.HexColor("#0B2E59")
NAVY600 = colors.HexColor("#1D4E89")
SAFFRON = colors.HexColor("#E8772E")
BORDER = colors.HexColor("#E2E8F0")
CANVAS = colors.HexColor("#F5F7FA")
MUTED = colors.HexColor("#475569")
SEV_COL = {"CRITICAL": colors.HexColor("#B91C1C"), "MAJOR": colors.HexColor("#B45309"),
           "MINOR": colors.HexColor("#1D4ED8"), "INFO": colors.HexColor("#475569")}
STATUS_COL = {"VERIFIED": "#15803D", "MISMATCH_DETECTED": "#B91C1C", "EXPIRED": "#C2410C",
              "VERIFICATION_PENDING": "#1D4ED8", "SOURCE_UNAVAILABLE": "#475569", "MANUAL_REVIEW_REQUIRED": "#B45309",
              "NOT_APPLICABLE": "#6B7280", "PRESENT": "#15803D", "MISSING": "#B91C1C", "INVALID": "#B91C1C",
              "NOT_REQUIRED": "#6B7280", "PASS": "#15803D", "FAIL": "#B91C1C", "SKIPPED": "#6B7280"}

DISCLAIMER = ("This report is generated by VeriSense, an AI-assisted decision-support prototype. All findings are "
              "ADVISORY indicators produced by automated checks (document AI, rule engine and issuing-authority "
              "verification) and require review by an authorised AICTE officer. Norms and clause references are "
              "illustrative and configurable. The final decision rests solely with the competent AICTE authority.")


def _p(text, style):
    return Paragraph(escape(str(text if text is not None else "-")), style)


def _badge(text, styles):
    col = STATUS_COL.get(str(text), "#0F172A")
    return Paragraph(f'<font color="{col}"><b>{escape(str(text))}</b></font>', styles["cell"])


def build_report_pdf(app, report: dict, generated_for=None) -> bytes:
    buf = io.BytesIO()
    ss = getSampleStyleSheet()
    styles = {
        "title": ParagraphStyle("t", parent=ss["Title"], fontName="Helvetica-Bold", fontSize=15, textColor=NAVY,
                                alignment=TA_CENTER, spaceAfter=2),
        "sub": ParagraphStyle("s", parent=ss["Normal"], fontSize=8.5, textColor=MUTED, alignment=TA_CENTER),
        "h2": ParagraphStyle("h2", parent=ss["Heading2"], fontName="Helvetica-Bold", fontSize=11.5, textColor=NAVY,
                             spaceBefore=10, spaceAfter=4),
        "body": ParagraphStyle("b", parent=ss["Normal"], fontSize=8.8, leading=11.5),
        "cell": ParagraphStyle("c", parent=ss["Normal"], fontSize=7.6, leading=9.4),
        "cellb": ParagraphStyle("cb", parent=ss["Normal"], fontSize=7.6, leading=9.4, fontName="Helvetica-Bold"),
        "small": ParagraphStyle("sm", parent=ss["Normal"], fontSize=7, leading=9, textColor=MUTED),
        "adv": ParagraphStyle("adv", parent=ss["Normal"], fontSize=8, leading=10.5, textColor=colors.HexColor("#7C2D12"),
                              backColor=colors.HexColor("#FFF7ED"), borderColor=SAFFRON, borderWidth=0.6,
                              borderPadding=5, spaceBefore=4, spaceAfter=6),
    }
    inst = app.institution
    summ = report.get("summary", {})
    generated = datetime.now(timezone.utc).strftime("%d %b %Y %H:%M UTC")

    def on_page(canvas, doc):
        canvas.saveState()
        w, h = A4
        canvas.setFillColor(NAVY)
        canvas.rect(0, h - 9 * mm, w, 9 * mm, stroke=0, fill=1)
        canvas.setFillColor(SAFFRON)
        canvas.rect(0, h - 10 * mm, w, 1 * mm, stroke=0, fill=1)
        canvas.setFillColor(colors.white)
        canvas.setFont("Helvetica-Bold", 8.5)
        canvas.drawString(14 * mm, h - 6 * mm, "AICTE VeriSense — Preliminary Validation Report (Advisory)")
        canvas.setFont("Helvetica", 8)
        canvas.drawRightString(w - 14 * mm, h - 6 * mm, app.application_no)
        canvas.setFillColor(MUTED)
        canvas.setFont("Helvetica", 7)
        canvas.drawString(14 * mm, 8 * mm, "Advisory decision support — requires officer review. Final decision rests with the competent AICTE authority.")
        canvas.drawRightString(w - 14 * mm, 8 * mm, f"Page {doc.page}")
        canvas.restoreState()

    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=14 * mm, rightMargin=14 * mm, topMargin=16 * mm,
                            bottomMargin=15 * mm, title=f"VeriSense report {app.application_no}",
                            author="AICTE VeriSense (prototype)", subject="Preliminary Validation Report (Advisory)")
    el = []
    el.append(Paragraph("AICTE VeriSense — Preliminary Validation Report (Advisory)", styles["title"]))
    el.append(Paragraph(
        f"Application {escape(app.application_no)} &nbsp;|&nbsp; Generated {generated} &nbsp;|&nbsp; Ruleset "
        f"{escape(str(report.get('rulesetVersion')))} &nbsp;|&nbsp; Validation run {escape(str(report.get('generatedAt', ''))[:19])}",
        styles["sub"]))
    el.append(Spacer(1, 4))
    el.append(Paragraph("<b>ADVISORY:</b> " + escape(DISCLAIMER), styles["adv"]))

    # institution details
    el.append(Paragraph("1. Institution and application", styles["h2"]))
    rows = [
        ["Institution", inst.name, "AICTE Permanent ID", inst.permanent_id],
        ["Type", inst.type, "Region", inst.region],
        ["City / State", ", ".join(x for x in (inst.city, inst.state) if x) or "-", "Established", inst.established_year or "-"],
        ["Society / Trust", inst.trust_name or "-", "Category", app.category],
        ["Academic year", app.academic_year, "Current status", app.status],
        ["Submitted", (app.submitted_at.strftime("%d %b %Y") if app.submitted_at else "-"),
         "Assigned officer", app.assigned_officer or "-"],
    ]
    t = Table([[_p(a, styles["cellb"]), _p(b, styles["cell"]), _p(c, styles["cellb"]), _p(d, styles["cell"])] for a, b, c, d in rows],
              colWidths=[30 * mm, 62 * mm, 32 * mm, 58 * mm])
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, BORDER), ("BACKGROUND", (0, 0), (0, -1), CANVAS),
                           ("BACKGROUND", (2, 0), (2, -1), CANVAS), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    el.append(t)

    # summary
    el.append(Paragraph("2. Summary", styles["h2"]))
    band = summ.get("riskBand", "-")
    band_col = {"LOW": "#15803D", "MEDIUM": "#B45309", "HIGH": "#B91C1C"}.get(band, "#0F172A")
    cells = [
        ("Compliance score", f"{summ.get('complianceScore', 0):.0f} / 100"),
        ("Risk score", f'<font color="{band_col}">{summ.get("riskScore", 0):.0f} ({band})</font>'),
        ("Open findings", f"{summ.get('findingsOpen', 0)}  (C {summ.get('critical', 0)} / Mj {summ.get('major', 0)} / Mn {summ.get('minor', 0)})"),
        ("Documents", f"{summ.get('documents', 0)}  (verified {summ.get('verified', 0)}, pending {summ.get('pending', 0)}, mismatch {summ.get('mismatches', 0)})"),
        ("Rules", f"pass {summ.get('rulesPassed', 0)} / fail {summ.get('rulesFailed', 0)} / skipped {summ.get('rulesSkipped', 0)}"),
        ("Scrutiny date", report.get("scrutinyDate", "-")),
    ]
    st = Table([[Paragraph(f"<b>{a}</b>", styles["cell"]), Paragraph(b, styles["cell"])] for a, b in cells],
               colWidths=[40 * mm, 142 * mm])
    st.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, BORDER), ("BACKGROUND", (0, 0), (0, -1), CANVAS)]))
    el.append(st)
    if report.get("recommendation"):
        r = report["recommendation"]
        el.append(Spacer(1, 4))
        el.append(Paragraph(f"<b>Officer recommendation:</b> {escape(r.get('action', ''))} by {escape(str(r.get('decidedByName') or r.get('decidedBy')))} "
                            f"on {escape(str(r.get('decidedAt', ''))[:10])} — {escape(r.get('note', ''))}", styles["body"]))
    if report.get("decision"):
        r = report["decision"]
        el.append(Paragraph(f"<b>Recorded decision:</b> {escape(r.get('action', ''))} by {escape(str(r.get('decidedByName') or r.get('decidedBy')))} "
                            f"on {escape(str(r.get('decidedAt', ''))[:10])} — {escape(r.get('note', ''))}", styles["body"]))

    # checklist
    el.append(Paragraph("3. Document checklist", styles["h2"]))
    data = [[_p(h, styles["cellb"]) for h in ("Document", "Required", "Status", "Clause (illustrative)")]]
    for c in report.get("checklist", []):
        data.append([_p(c.get("label"), styles["cell"]),
                     _p("Mandatory" if c.get("mandatory") else ("Conditional" if c.get("conditional") else "Optional"), styles["cell"]),
                     _badge(c.get("status"), styles), _p(c.get("clause"), styles["small"])])
    ct = Table(data, colWidths=[55 * mm, 21 * mm, 31 * mm, 75 * mm], repeatRows=1)
    ct.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, BORDER), ("BACKGROUND", (0, 0), (-1, 0), CANVAS),
                            ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    el.append(ct)

    # findings
    findings = [f for f in report.get("findings", []) if f.get("status") != "DISMISSED"]
    order = {"CRITICAL": 0, "MAJOR": 1, "MINOR": 2, "INFO": 3}
    findings.sort(key=lambda f: (order.get(f.get("severity"), 9), f.get("id", 0)))
    el.append(Paragraph(f"4. Findings and deficiencies ({len(findings)})", styles["h2"]))
    if not findings:
        el.append(Paragraph("No findings.", styles["body"]))
    for i, f in enumerate(findings, 1):
        sev = f.get("severity", "INFO")
        head = Paragraph(
            f'<font color="{SEV_COL.get(sev, MUTED).hexval().replace("0x", "#")}"><b>[{sev}]</b></font> '
            f"<b>{i}. {escape(f.get('title', ''))}</b> &nbsp;<font color='#475569' size='7'>{escape(f.get('kind', ''))} · "
            f"{escape(f.get('ruleId') or 'pipeline')} · status {escape(f.get('status', ''))}</font>", styles["body"])
        body = [head, Paragraph(escape(f.get("reason", "")), styles["cell"])]
        if f.get("clause"):
            body.append(Paragraph(f"<i>Clause: {escape(f['clause'])}</i>", styles["small"]))
        ev_rows = []
        for e in f.get("evidence", []):
            if e.get("type") == "RULE":
                continue
            sv = []
            if e.get("submitted") is not None:
                sv.append(f"submitted: <b>{escape(str(e['submitted']))}</b>")
            if e.get("reference") is not None:
                sv.append(f"record/source: <b>{escape(str(e['reference']))}</b>")
            if e.get("page"):
                sv.append(f"page {e['page']}")
            if e.get("excerpt"):
                sv.append(f"“{escape(str(e['excerpt'])[:180])}”")
            ev_rows.append([_p(e.get("type"), styles["small"]), Paragraph(escape(e.get("label", "")) + ("<br/>" + " · ".join(sv) if sv else ""), styles["cell"])])
        if ev_rows:
            et = Table(ev_rows, colWidths=[24 * mm, 152 * mm])
            et.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.3, BORDER), ("BACKGROUND", (0, 0), (0, -1), CANVAS),
                                    ("VALIGN", (0, 0), (-1, -1), "TOP")]))
            body.append(et)
        if f.get("reviewerNote"):
            body.append(Paragraph(f"<b>Reviewer note:</b> {escape(f['reviewerNote'])}", styles["cell"]))
        body.append(Spacer(1, 5))
        el.append(KeepTogether(body))

    # verification
    el.append(Paragraph("5. Verification with issuing authorities", styles["h2"]))
    data = [[_p(h, styles["cellb"]) for h in ("Document", "Status", "Source", "Method", "Checked at", "Note")]]
    for v in report.get("verifications", []):
        data.append([_p(f"{v.get('docTypeLabel') or v.get('docType')}\n{v.get('fileName') or ''}", styles["cell"]),
                     _badge(v.get("status"), styles), _p(v.get("source") or "-", styles["cell"]),
                     _p(v.get("method") or "-", styles["cell"]), _p(str(v.get("checkedAt") or "-")[:19], styles["cell"]),
                     _p((v.get("reason") or "")[:160], styles["small"])])
    vt = Table(data, colWidths=[42 * mm, 30 * mm, 30 * mm, 20 * mm, 24 * mm, 36 * mm], repeatRows=1)
    vt.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, BORDER), ("BACKGROUND", (0, 0), (-1, 0), CANVAS),
                            ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    el.append(vt)

    # rules
    el.append(PageBreak())
    el.append(Paragraph(f"6. Rules applied (ruleset {escape(str(report.get('rulesetVersion')))})", styles["h2"]))
    data = [[_p(h, styles["cellb"]) for h in ("Rule", "Result", "Detail", "Clause (illustrative)")]]
    for r in report.get("rulesApplied", []):
        data.append([_p(f"{r.get('ruleId')} v{r.get('version', 1)}\n{r.get('name', '')}", styles["cell"]),
                     _badge(r.get("result"), styles), _p(r.get("detail"), styles["cell"]), _p(r.get("clause"), styles["small"])])
    rt = Table(data, colWidths=[40 * mm, 16 * mm, 76 * mm, 50 * mm], repeatRows=1)
    rt.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, BORDER), ("BACKGROUND", (0, 0), (-1, 0), CANVAS),
                            ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    el.append(rt)
    rc = report.get("recordsChecked") or {}
    if rc:
        el.append(Spacer(1, 4))
        el.append(Paragraph("<b>Institutional records consulted:</b> " + escape(", ".join(f"{k} ({v})" for k, v in rc.items())), styles["small"]))

    el.append(Paragraph("7. Disclaimer", styles["h2"]))
    el.append(Paragraph(escape(DISCLAIMER), styles["body"]))
    if generated_for is not None:
        el.append(Spacer(1, 6))
        el.append(Paragraph(f"Exported by {escape(generated_for.full_name)} ({escape(generated_for.role)}) on {generated}. "
                            "Every export is recorded in the tamper-evident audit log.", styles["small"]))
    doc.build(el, onFirstPage=on_page, onLaterPages=on_page)
    return buf.getvalue()
